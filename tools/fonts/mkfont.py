#!/usr/bin/env python3
"""Rasterises a TrueType font into a C font for the DM-32 firmware (graphics/gfxFont.h).

Each glyph is stored at 4 bits per pixel (16 levels of coverage, anti-aliased), cropped to its ink box, rows packed
two pixels per byte with the left pixel in the high nibble. Run from the repository root:

  py tools/fonts/mkfont.py tools/fonts/ttf/RobotoCondensed-VF.ttf 24 font_roboto24 --weight Regular
  py tools/fonts/mkfont.py tools/fonts/ttf/RobotoCondensed-VF.ttf 46 font_roboto46_bold --weight Bold --chars "0123456789. "

The output goes to src/graphics/fonts/<name>.c; declare the font in graphics/fonts/fonts.h.
"""
import argparse
import os

from PIL import Image, ImageDraw, ImageFont

HERE = os.path.dirname(os.path.abspath(__file__))
OUT_DIR = os.path.join(HERE, '..', '..', 'src', 'graphics', 'fonts')
HEADER = '''/*
 * Generated by tools/fonts/mkfont.py from {ttf} ({weight}), {size} px. Do not edit.
 * The font is under its own licence: tools/fonts/ttf/{licence}.
 */

#include "font.h"
#include "hw.h"

'''


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('ttf')
    ap.add_argument('size', type=int, help='pixel size (em)')
    ap.add_argument('name', help='C name of the font, e.g. font_roboto24')
    ap.add_argument('--weight', default='Regular', help='variation name of a variable font')
    ap.add_argument('--chars', help='characters to include (default: printable ASCII)')
    ap.add_argument('--licence', default='OFL-RobotoCondensed.txt')
    args = ap.parse_args()

    font = ImageFont.truetype(args.ttf, args.size)
    try:
        font.set_variation_by_name(args.weight)
    except (OSError, AttributeError):
        pass
    ascent, descent = font.getmetrics()

    chars = sorted(set(args.chars)) if args.chars else [chr(c) for c in range(0x20, 0x7F)]
    codes = [ord(c) for c in chars]
    first, last = codes[0], codes[-1]

    glyphs = []
    bitmap = bytearray()
    for code in range(first, last + 1):
        ch = chr(code)
        if code not in codes:
            glyphs.append((0, 0, 0, 0, 0, 0xFFFFFFFF))  # not in the font
            continue
        advance = int(round(font.getlength(ch)))
        x0, y0, x1, y1 = font.getbbox(ch, anchor='ls')
        w, h = max(0, x1 - x0), max(0, y1 - y0)
        if w == 0 or h == 0:
            glyphs.append((0, 0, 0, 0, advance, len(bitmap)))
            continue
        im = Image.new('L', (w, h), 0)
        ImageDraw.Draw(im).text((-x0, -y0), ch, font=font, fill=255, anchor='ls')
        offset = len(bitmap)
        px = im.load()
        for y in range(h):
            row = [(px[x, y] + 8) // 17 for x in range(w)]  # 0..15
            if w % 2:
                row.append(0)
            for x in range(0, len(row), 2):
                bitmap.append((row[x] << 4) | row[x + 1])
        glyphs.append((w, h, x0, ascent + y0, advance, offset))

    out = [HEADER.format(ttf=os.path.basename(args.ttf), weight=args.weight, size=args.size, licence=args.licence)]
    out.append('static const uint8_t bitmap[] FLASH_CONST = {\n')
    for i in range(0, len(bitmap), 24):
        out.append('\t' + ', '.join('0x%02X' % b for b in bitmap[i:i + 24]) + ',\n')
    out.append('};\n\n')
    out.append('static const font_glyph_t glyphs[] FLASH_CONST = {\n')
    for code, (w, h, xo, yo, adv, off) in zip(range(first, last + 1), glyphs):
        label = chr(code) if 0x20 < code < 0x7F and chr(code) not in '\\\'' else 'U+%04X' % code
        out.append('\t{ %d, %d, %d, %d, %d, %s }, // %s\n' % (w, h, xo, yo, adv, ('FONT_GLYPH_NONE' if off == 0xFFFFFFFF else str(off)), label))
    out.append('};\n\n')
    out.append('const font_t %s FLASH_CONST = { %d, %d, 0x%04X, %d, glyphs, bitmap };\n'
               % (args.name, ascent + descent, ascent, first, last - first + 1))

    os.makedirs(OUT_DIR, exist_ok=True)
    path = os.path.join(OUT_DIR, args.name + '.c')
    with open(path, 'w', encoding='utf-8', newline='\n') as f:
        f.write(''.join(out))
    print('%s: %d glyphs, %d bytes of bitmap, line %d px' % (path, len(codes), len(bitmap), ascent + descent))


if __name__ == '__main__':
    main()
