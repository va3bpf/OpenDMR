#!/usr/bin/env python3
"""Generates the text tables of the firmware (src/ui/text/) from tools/text/languages/en.json, and checks the other
language files there (docs/i18n.en.md).

    py tools/text/gen_text.py

ui/text/text.h       TEXT_x ids, in the order of en.json
ui/text/text_en.c    the English strings, built into the firmware (the default language and the fallback)
ui/text/text_keys.c  the FNV-1a hash of each TEXT_x name with its id, sorted by hash: the radio finds the strings of
                     a language file written by the CPS with it (services/language.c)

The other languages are not built in: the CPS writes their .json to the radio. A new string goes into en.json (and
into the other languages when known); the ids may change, the hashes of the names do not.
"""
import glob
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import langfile  # noqa: E402

ROOT = os.path.join(HERE, '..', '..', 'src')
LANGUAGES = os.path.join(HERE, 'languages')
OUT = os.path.join(ROOT, 'ui', 'text')
HEADER = '// Generated by tools/text/gen_text.py from tools/text/languages/en.json: do not edit\n'


def write(path, text):
    with open(path, 'w', encoding='utf-8', newline='\n') as f:
        f.write(text)


def c_string(value):
    out = '"'
    for ch in value:
        if ch in '"\\':
            out += '\\' + ch
        elif ch == '\n':
            out += '\\n'
        elif ord(ch) < 0x20:
            out += '\\x%02x""' % ord(ch)
        else:
            out += ch
    return out + '"'


def main():
    english = langfile.load(os.path.join(LANGUAGES, 'en.json'))
    errors, _ = langfile.check(english)
    if errors:
        raise SystemExit('en.json: ' + '; '.join(errors))
    names = list(english['strings'])

    failed = False
    for path in sorted(glob.glob(os.path.join(LANGUAGES, '*.json'))):
        if os.path.basename(path) == 'en.json':
            continue
        errors, warnings = langfile.check(langfile.load(path), english)
        for line in errors:
            print('%s: error: %s' % (os.path.basename(path), line))
        for line in warnings:
            print('%s: %s' % (os.path.basename(path), line))
        failed = failed or bool(errors)

    lines = [HEADER, '#ifndef DM32_TEXT_H', '#define DM32_TEXT_H', '', '#include <stdint.h>', '',
             '// Text ids: text(TEXT_x) is the string in the current language (text.c)', 'typedef enum {']
    lines += ['    %s,' % name for name in names]
    lines += ['    TEXT_COUNT', '} text_id_t;', '',
              'const char *text(text_id_t id); // in the current language (text.c)', '',
              'extern const char *const text_en[TEXT_COUNT];', '',
              '// FNV-1a hashes of the TEXT_x names, sorted, and the id of each (text_keys.c)',
              'extern const uint32_t text_key_hashes[TEXT_COUNT];',
              'extern const uint16_t text_key_ids[TEXT_COUNT];', '', '#endif', '']
    write(os.path.join(OUT, 'text.h'), '\n'.join(lines))

    lines = [HEADER, '#include "text.h"', '', 'const char *const text_en[TEXT_COUNT] = {']
    lines += ['    [%s] = %s,' % (name, c_string(english['strings'][name])) for name in names]
    lines += ['};', '']
    write(os.path.join(OUT, 'text_en.c'), '\n'.join(lines))

    keys = sorted((langfile.fnv1a(name), name) for name in names)
    lines = [HEADER, '#include "text.h"', '', 'const uint32_t text_key_hashes[TEXT_COUNT] = {']
    lines += ['    0x%08Xu, // %s' % (h, name) for h, name in keys]
    lines += ['};', '', 'const uint16_t text_key_ids[TEXT_COUNT] = {']
    lines += ['    %s,' % name for _, name in keys]
    lines += ['};', '']
    write(os.path.join(OUT, 'text_keys.c'), '\n'.join(lines))

    print('%d strings' % len(names))
    if failed:
        raise SystemExit(1)


if __name__ == '__main__':
    main()
