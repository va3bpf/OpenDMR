chinese = dict(read('chinese.h', 'utf-8') + [(name, zh) for name, _, zh, _ in EXTRA])
spanish = dict(read('spanish.h', 'cp1252') + [(name, es) for name, _, _, es in EXTRA])
names = [name for name, _ in english]

# The format specifiers must be the same as in English, or a printf would read the wrong argument
for name, en in english:
    for language, table in (('chinese', chinese), ('spanish', spanish)):
        if (name in table) and (SPEC.findall(table[name]) != SPEC.findall(en)):
            raise SystemExit('%s: %s has %s, English has %s' % (name, language, SPEC.findall(table[name]),
                                                                SPEC.findall(en)))

# A string a language does not have yet: NULL, so text() falls back to English (text.c)
for language, table in (('chinese', chinese), ('spanish', spanish)):
    missing = [name for name in names if table.get(name) is None]
    if missing:
        print('%s is missing %d: %s' % (language, len(missing), ', '.join(missing)))

