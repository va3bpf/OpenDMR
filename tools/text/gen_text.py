HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, '..', '..', 'src')
LANGUAGES = os.path.join(HERE, 'languages')  # english.h, chinese.h, spanish.h of the ucos firmware
OUT = os.path.join(ROOT, 'ui', 'text')
FIELD = re.compile(r'^\.(\w+)\s*=\s*"((?:[^"\\]|\\.)*)"', re.M)
SPEC = re.compile(r'%[-+ #0-9.*]*[a-zA-Z%]')  # the format specifiers of a string

HEADER = '// Generated by tools/text/gen_text.py from tools/text/languages/%s: do not edit\n'


def read(name, encoding):
    with open(os.path.join(LANGUAGES, name), encoding=encoding) as f:
        return FIELD.findall(f.read())


def write(path, text):
    with open(path, 'w', encoding='utf-8', newline='\n') as f:
        f.write(text)


